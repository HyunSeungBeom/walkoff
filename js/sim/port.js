// 장면 계산(sim)이 부를 때 읽는 바깥 값(포트, 2026-11-06 코드 나누기 4단계). sim은 판 상태(game·settings)와 카메라를 가져오지 않고
// main.js가 처음에 connect로 이어 준다. 전에 main.js 안에서 읽던 그 순간에 읽어서 동작은 그대로다. 이어 주기 전에는 아래 기본값이다
export const port = {
  eye: () => ({ x: 0, y: 1.4, z: -3.2 }),   // 카메라 자리(잡은 공이 수비수 몸에 가리는지, 차올린 발 밑창이 보이는지)
  lefty: () => false,                       // 지금 공을 던진 투수가 좌완인지(글러브 손, 움찔하며 비키는 쪽)
  pitchT: () => 0,                          // 와인드업 시작부터 흐른 시간(초). 투수가 수비로 넘어갈 때 투구 자세에서 섞는다
  batSide: () => 1,                         // 지금 타석(우타 1, 좌타 -1)
  batterShift: () => 0,                     // 폰은 타자를 화면 안으로 당겨 그린다(m). 친 타자도 처음 8m 동안 그만큼 옮겨 그린다
};
export const connect = (o) => Object.assign(port, o);
